/* ── Grading ──────────────────────────────────────────────────── */

export type AnswerBand = 'excellent' | 'good' | 'average' | 'weak' | 'missing'
export type OverallBand = 'excellent' | 'strong' | 'developing' | 'needs_work'

export interface AnswerEvaluation {
  questionId: string
  score: number
  band: AnswerBand
  strengths: string[]
  improvements: string[]
  feedback: string
}

export interface SkillScore {
  skill: string
  score: number
  questions: number
}

export interface TypeScore {
  type: QuestionType
  score: number
  questions: number
}

/** Per-question speech metrics captured by the interview mic. */
export interface SpeechMetric {
  questionId: string
  type: QuestionType
  text: string
  /** Total seconds the candidate spoke on this question. */
  spokenSeconds: number
  /** Words in the submitted (transcribed) answer. */
  wordCount: number
  /** Average recognition confidence 0..1, or null when the browser omits it. */
  confidence: number | null
}

/** Proctoring flag logged during the session (warning only, never scored). */
export interface SpeechEventInput {
  id: string
  type: string
  detail: string
  at: number
}

/** Attention stats sent with the grade request (drives the confidence meter). */
export interface FocusInput {
  /** Wall-clock session length in seconds (includes freeze time). */
  sessionSeconds: number
  /** Cumulative milliseconds each proctor flag type was active. */
  flaggedMs: Record<string, number>
}

/** Camera-confidence summary persisted on the result and shown in the report. */
export interface ProctorSummary {
  /** 0–100 — falls as the candidate looks away / leaves the tab. */
  confidence: number
  sessionSeconds: number
  /** Total attention flags across all types, in seconds (rounded). */
  flaggedSeconds: number
  /** Per-type flagged seconds. */
  byType: Record<string, number>
  /** Number of flag events logged during the session. */
  flags: number
}

export interface GradingResult {
  overall: number
  band: OverallBand
  summary: string
  evaluations: AnswerEvaluation[]
  skills: SkillScore[]
  types: TypeScore[]
  answered: number
  total: number
  /** Speech performance per spoken/written-with-dictation question. */
  speech?: SpeechMetric[]
  /** Camera-confidence meter (0–100). */
  proctor?: ProctorSummary
}

export interface GradeQuestion {
  id: string
  text: string
  skill: string
  topic: string
  type: QuestionType
  difficulty: Difficulty
}

export interface GradeAnswer {
  questionId: string
  answer: string
}

export interface GradeInput {
  role: string
  questions: GradeQuestion[]
  answers: GradeAnswer[]
  speech?: SpeechMetric[]
  events?: SpeechEventInput[]
  focus?: FocusInput
}

export interface GradeResultResponse {
  mode: 'ai' | 'heuristic'
  provider: 'claude' | 'heuristic'
  result: GradingResult
}

export async function gradeInterviewRemote(
  input: GradeInput
): Promise<GradeResultResponse> {
  return api<GradeResultResponse>('/api/interview/grade', {
    method: 'POST',
    body: input,
  })
}

